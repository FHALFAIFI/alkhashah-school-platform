/**
 * حالات مخصص البند المالي ونصوصها العربية (v2.4.1 §4).
 *
 * السبب الجذري لشكوى «المتبقي غير ظاهر»: بنود `financial_items` في الإنتاج بلا مخصص
 * (`allocated_amount IS NULL`)، فيُحسب المتبقي `null` ويُعرض «—» بلا تفسير، وتختفي أعمدة
 * «المتبقي قبل/بعد العملية» من دفتر البند. السلوك الحسابي صحيح — الناقص هو **التفسير
 * والإجراء**: لماذا لا يمكن الاحتساب، وكيف يُصحَّح.
 *
 * القاعدة المحسومة (D-043 وما قبلها): **`null` ليس صفراً**. البند بلا مخصص لا يُحتسب له
 * متبقٍ ولا نسبة استهلاك؛ والبند بمخصص صفر حالةٌ مختلفة تماماً — كل صرف عليه تجاوز.
 *
 * وحدة خالصة: بلا قاعدة بيانات وبلا React، فتُختبر وحدوياً بالكامل.
 */

/** الحالات الثلاث المتمايزة للمخصص — `overspent` مشتق لا حالة مستقلة */
export type AllocationState = "none" | "zero" | "positive";

/** تصنيف المخصص: غير محدد / صفر / موجب. `null` و`0` لا يُخلط بينهما أبداً. */
export function allocationState(allocated: number | null): AllocationState {
  if (allocated === null) return "none";
  return allocated === 0 ? "zero" : "positive";
}

/* ── النصوص العربية الموحّدة ────────────────────────────────────────────────
 * تُستعمل في الشاشات والتقارير والطباعة معاً حتى لا تتفرع الصياغة بين السطوح.
 */

/** قيمة «المخصص» حين لا مخصص — بديل «—» المجرّد */
export const ALLOCATION_NONE_VALUE = "غير محدد";

/** تفسير حالة «لا مخصص» — يظهر تحت البطاقة وفي الجداول والتقارير */
export const ALLOCATION_NONE_HINT = "لم يتم تحديد مخصص لهذا البند";

/** تفسير تعذّر احتساب المتبقي — بديل «—» في خانة المتبقي */
export const REMAINING_UNAVAILABLE = "لا يمكن احتسابه قبل تحديد المخصص";

/** نص الإجراء المصحّح */
export const SET_ALLOCATION_CTA = "تحديد المخصص";

/** تحذير الصرف على بند مخصصه صفر */
export const ZERO_ALLOCATION_WARNING = "يوجد صرف على بند مخصصه صفر — كل مبلغ مصروف يُعدّ تجاوزاً";

/** تنبيه خفض المخصص إلى ما دون المصروف الفعلي (يتطلب تأكيداً صريحاً) */
export function allocationBelowSpentWarning(proposed: number, spent: number): string {
  return `المخصص المقترح (${proposed}) أقل من المصروف الفعلي (${spent}) — سيصبح البند متجاوزاً فور الحفظ`;
}

/**
 * رسالة نتيجة حفظ المصروف (§4.7) — المستخدم يفهم الأثر دون الانتقال لشاشة أخرى.
 * `remainingAfter === null` يعني أن البند بلا مخصص فلا متبقٍ يُحتسب.
 */
export function expenseSavedMessage(remainingAfter: number | null, formatted?: string): string {
  if (remainingAfter === null) return "تم حفظ المصروف — لا يمكن احتساب المتبقي لأن المخصص غير محدد";
  return `تم حفظ المصروف — المتبقي بعد العملية: ${formatted ?? remainingAfter} ريال`;
}
