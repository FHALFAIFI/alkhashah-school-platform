/**
 * قاعدة إبطال التخزين بعد إجراءات الخادم — D-049 (v2.4.1) ثم **D-053** (v2.5.0).
 *
 * ── ما اكتُشف على بروفة نسخة الإنتاج (D-049) ────────────────────────────────
 * استدعاء `revalidatePath(p)` لمسارٍ **هو الصفحة المفتوحة أمام المستخدم** يدفع موجّه Next
 * إلى إعادة جلب ذلك المسار فوراً، فيُلغى طلب إجراء الخادم الذي ما زال يُدفَّق
 * (`net::ERR_ABORTED`) قبل أن يستهلك العميل قيمته المُعادة. النتيجة على بناء الإنتاج:
 * **الكتابة تنجح، والرسالة لا تظهر، والصفحة لا تتحدث، ومؤشر الانتظار يبقى مرفوعاً**
 * فتبقى عناصر القائمة معطّلة حتى إعادة تحميل يدوية.
 *
 * أُثبت ذلك تجريبياً: صورة إنتاج واحدة، الفرق الوحيد بينها وبين الأخرى حذف
 * `revalidatePath("/budget")` من إجراء حفظ المصروف — ومعه ظهرت الرسالة.
 *
 * ── لماذا لم يكفِ استثناء «المسار الحالي» وحده (D-053) ──────────────────────
 * v2.4.1 استثنى المسار الحالي وأبقى إبطال المسارات الأخرى. ثم كشفت بروفة الفحص أن
 * إبطال مسار **أب** (`/building/maintenance`) يبطل شجرة المسار المفتوح
 * (`/building/maintenance/inspect`) فيعيد السباق نفسه؛ وأن إجراءً واحداً قد يُستدعى من
 * مسارين مختلفين فلا يعرف أيهما «الحالي» أصلاً. أي استثناء يعتمد على معرفة موضع النداء
 * هش بحكم التصميم.
 *
 * وفي هذه المنصة تحديداً لا يشتري الإبطال شيئاً: كل صفحة `dynamic = "force-dynamic"`،
 * ولا يُضبط `experimental.staleTimes`، فذاكرة موجّه العميل لا تحتفظ بحمولة مسار ديناميكي
 * أصلاً. الانتقال إلى أي صفحة أخرى يعيد تصييرها من قاعدة البيانات في كل الأحوال.
 *
 * ── القاعدة النهائية (D-053) ────────────────────────────────────────────────
 * • **لا `revalidatePath` في طبقة التطبيق إطلاقاً.** يثبّتها
 *   `tests/unit/no-revalidate-in-actions.test.ts` فلا تعود ملفاً ملفاً.
 * • تحديث الصفحة بعد نجاح الإجراء مسؤولية العميل: `useRefreshOnSuccess`
 *   (`components/form-reset.ts`) — طلب واحد يبدأ **بعد** استقرار النتيجة فلا يزاحم تدفّقها.
 * • الإجراء الذي ينتهي بـ`redirect()` لا يحتاج تحديثاً — الوجهة تُصيَّر من جديد.
 */

/**
 * لا شيء يُبطَل. الدالة باقية كنقطة توثيق واحدة يشير إليها المراجعون، ولتفشل بوضوح لو
 * حاول أحد إعادة الإبطال عبرها بدل استدعاء `revalidatePath` مباشرةً.
 */
export function revalidateOtherPaths(_paths: string[], _opts: { except: string | string[] }): never {
  throw new Error(
    "D-053: لا إبطال لمسارات من إجراءات الخادم — حدّث الصفحة من العميل عبر useRefreshOnSuccess",
  );
}
