import { revalidatePath } from "next/cache";

/**
 * قاعدة إبطال التخزين بعد إجراءات الخادم (v2.4.1 §F — D-049).
 *
 * ── ما اكتُشف على بروفة نسخة الإنتاج ────────────────────────────────────────
 * استدعاء `revalidatePath(p)` لمسارٍ **هو الصفحة المفتوحة أمام المستخدم** يدفع موجّه Next
 * إلى إعادة جلب ذلك المسار فوراً، فيُلغى طلب إجراء الخادم الذي ما زال يُدفَّق
 * (`net::ERR_ABORTED`) قبل أن يستهلك العميل قيمته المُعادة. النتيجة على بناء الإنتاج:
 * **الكتابة تنجح، والرسالة لا تظهر، والصفحة لا تتحدث، ومؤشر الانتظار يبقى مرفوعاً**
 * فتبقى عناصر القائمة معطّلة حتى إعادة تحميل يدوية.
 *
 * أُثبت ذلك تجريبياً: صورة إنتاج واحدة، الفرق الوحيد بينها وبين الأخرى حذف
 * `revalidatePath("/budget")` من إجراء حفظ المصروف — ومعه ظهرت الرسالة.
 *
 * ── القاعدة ─────────────────────────────────────────────────────────────────
 * • صفحات هذه المنصة كلها `dynamic = "force-dynamic"`، فلا تُخبَّأ على الخادم أصلاً؛
 *   `revalidatePath` عليها لا يضيف تحديثاً بل يضيف سباقاً.
 * • لذلك: **لا تُبطِل مسار الصفحة التي أُرسل منها الإجراء.** تحديثها مسؤولية العميل عبر
 *   `router.refresh()` بعد استقرار النتيجة — طلب واحد لا يزاحمه شيء.
 * • أبطِل المسارات **الأخرى** التي تأثرت (وثائق، قوائم، لوحات) كما كان.
 *
 * `revalidateOtherPaths` تجعل هذا القرار ظاهراً في موضع النداء بدل تعليق يسهل نسيانه.
 */
export function revalidateOtherPaths(paths: string[], opts: { except: string | string[] }): void {
  const except = new Set(Array.isArray(opts.except) ? opts.except : [opts.except]);
  for (const p of paths) {
    if (!except.has(p)) revalidatePath(p);
  }
}
