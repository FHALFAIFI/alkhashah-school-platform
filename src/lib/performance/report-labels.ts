/**
 * مسميات تقارير الأداء كما يطلبها المدير (v2.4.1 §1.4).
 *
 * صياغة المدير هي «تقرير تفصيلي للمعلم» و«تقرير تفصيلي وإحصائي للجميع». المنصة تضم
 * معلمين وموظفين إداريين معاً (D-019)، فالتسمية الفردية تتبع نوع المنسوب: «للمعلم»
 * لمن هو معلم و«للموظف» لغيره — فتظهر صياغة المدير حرفياً حيث تنطبق، ولا يُسمّى موظف
 * إداري «معلماً». التقرير الشامل يحمل صياغة المدير كما هي بلا تعديل.
 *
 * وحدة خالصة: بلا قاعدة بيانات وبلا React — تُستعمل في الشاشات والتقارير والاختبارات.
 */

import type { EmployeeType } from "@/lib/employee-type";

/** التقرير الفردي المفصّل — بصياغة المدير، متبعةً نوع المنسوب */
export function individualReportLabel(type: EmployeeType): string {
  return type === "معلم" ? "تقرير تفصيلي للمعلم" : "تقرير تفصيلي للموظف";
}

/** الصياغة الحرفية للتقرير الشامل */
export const OVERALL_REPORT_LABEL = "تقرير تفصيلي وإحصائي للجميع";

/** عناوين أقسام التقرير الشامل — أربعة أقسام بالترتيب الذي أقرّه المدير */
export const OVERALL_REPORT_SECTIONS = {
  summary: "أولاً: الملخص الإحصائي التنفيذي",
  strengthsWeaknesses: "ثانياً: تحليل نقاط القوة والضعف",
  training: "ثالثاً: توصيات التدريب والتطوير",
  appendix: "رابعاً: الملحق التفصيلي بالأسماء",
} as const;

/**
 * فئة النتيجة النهائية — من شرائح التوزيع المعتمدة في المنصة نفسها، لا تقدير لفظي
 * مخترع («ممتاز/جيد جداً»). الشريحة رقمية معلنة فيبقى التقرير قابلاً للمراجعة.
 */
export function resultBandLabel(percent: number | null): string {
  if (percent === null) return "لم يكتمل التقييم بعد";
  if (percent < 60) return "أقل من 60٪";
  if (percent < 75) return "60–74٪";
  if (percent < 90) return "75–89٪";
  return "90٪ فأعلى";
}

/**
 * توصية تدريبية مشتقة من معيار ضعيف متكرر — إعادة صياغة للمعيار نفسه لا اقتراح
 * برنامج تدريبي مُختلق. القرار التدريبي للمدير؛ التقرير يشير إلى موضعه فقط.
 */
export function trainingRecommendation(criterion: string, affectedPeople: number): string {
  return `«${criterion}» — ضعف متكرر لدى ${affectedPeople} من المنسوبين؛ يصلح موضوعاً لبرنامج تطوير مهني مشترك.`;
}
