/**
 * تسميات الحالة المعروضة للإجراءات التي «تعتمد وتقفل» في خطوة واحدة.
 *
 * قرار المصطلحات (المالك): عند إجراء يعتمد ويقفل السجل معاً تُعرض الحالة «معتمد ومقفل»
 * (والمؤنث «معتمدة ومقفلة»)، بينما يبقى الفعل «اعتماد وإقفال» وإعادة الفتح «إعادة فتح بسبب موثق».
 *
 * هذه دوال عرض فقط: القيمة المخزَّنة في قاعدة البيانات تبقى «معتمد»/«معتمدة» دون تغيير
 * (لا تُعدَّل البيانات ولا مفاتيح الصلاحيات) — فقط النص الظاهر للمستخدم يُوحَّد.
 */

/** حالة البرنامج المعروضة: «معتمد» (المخزَّنة) تُعرض «معتمد ومقفل» */
export function programStatusLabel(status: string): string {
  return status === "معتمد" ? "معتمد ومقفل" : status;
}

/** حالة اللجنة المعروضة: «معتمدة» (تشكيل معتمد ومقفل) تُعرض «معتمدة ومقفلة» */
export function committeeStatusLabel(status: string): string {
  return status === "معتمدة" ? "معتمدة ومقفلة" : status;
}

/** نص زر إعادة الفتح الموحَّد لكل إجراءات الاعتماد والإقفال */
export const REOPEN_LABEL = "إعادة فتح بسبب موثق";
