/**
 * صياغة الحالة الفعلية لشواهد البرنامج بالعربية الصحيحة — معلوماتية فقط، بلا هدف أو حصة أو
 * نسبة أو «متبقٍّ» (D-025). عدد الشواهد لا يحدد إمكانية إكمال البرنامج إطلاقاً.
 *
 * 0 → «لم يتم رفع أي شاهد حتى الآن»
 * 1 → «تم رفع شاهد واحد»
 * 2 → «تم رفع شاهدان»
 * 3–10 → «تم رفع N شواهد»
 * ‏≥11 → «تم رفع N شاهداً»
 */
export function evidenceCountPhrase(count: number): string {
  const n = Math.max(0, Math.floor(count));
  if (n === 0) return "لم يتم رفع أي شاهد حتى الآن";
  if (n === 1) return "تم رفع شاهد واحد";
  if (n === 2) return "تم رفع شاهدان";
  if (n <= 10) return `تم رفع ${n} شواهد`;
  return `تم رفع ${n} شاهداً`;
}
