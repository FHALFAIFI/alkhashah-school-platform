/**
 * دورة حياة بلاغ الصيانة (v2.3 §18, D-036) — وحدة نقية تستوردها الواجهة والخادم معاً.
 *
 * مسودة ← معتمد ← تم الإرسال ← تحت المعالجة ← تم الإصلاح | لم يتم الإصلاح ← مغلق.
 * «تحت المعالجة» يمكن العودة إليها من نتيجتي المعالجة (إعادة فتح المعالجة قبل الإغلاق).
 * البلاغ المغلق نهائي.
 */

export const ISSUE_STATUSES = [
  "مسودة",
  "معتمد",
  "تم الإرسال",
  "تحت المعالجة",
  "تم الإصلاح",
  "لم يتم الإصلاح",
  "مغلق",
] as const;

export type IssueStatus = (typeof ISSUE_STATUSES)[number];

/**
 * أولويات البلاغ — القائمة المغلقة نفسها المعروضة في نموذج الإنشاء. عُرّفت هنا في
 * v2.5.0 لأن مرشّح الأولوية في التقارير يحتاجها، ونسخها في موضعين يفتح باب اختلافهما.
 */
export const ISSUE_PRIORITIES = ["عالية", "متوسطة", "منخفضة"] as const;
export type IssuePriority = (typeof ISSUE_PRIORITIES)[number];

/** الانتقالات المسموحة من كل حالة — تُنفَّذ على الخادم وتُعرض في الواجهة من المصدر نفسه */
export const ISSUE_TRANSITIONS: Record<string, string[]> = {
  "مسودة": ["معتمد"],
  "معتمد": ["تم الإرسال", "تحت المعالجة"],
  "تم الإرسال": ["تحت المعالجة", "تم الإصلاح", "لم يتم الإصلاح"],
  "تحت المعالجة": ["تم الإصلاح", "لم يتم الإصلاح"],
  "تم الإصلاح": ["مغلق", "تحت المعالجة"],
  "لم يتم الإصلاح": ["مغلق", "تحت المعالجة"],
  "مغلق": [],
};

/** تسمية زر الانتقال في الواجهة */
export function transitionLabel(toStatus: string): string {
  switch (toStatus) {
    case "معتمد":
      return "اعتماد البلاغ";
    case "تم الإرسال":
      return "تسجيل الإرسال";
    case "تحت المعالجة":
      return "بدء المعالجة";
    case "تم الإصلاح":
      return "تسجيل الإصلاح";
    case "لم يتم الإصلاح":
      return "تسجيل عدم الإصلاح";
    case "مغلق":
      return "إغلاق البلاغ";
    default:
      return toStatus;
  }
}

/** البلاغ القائم (غير المغلق وغير المسودة) — يُحتسب في «بلاغات قائمة» والجاهزية */
export function isOpenIssueStatus(status: string): boolean {
  return status !== "مغلق" && status !== "مسودة";
}
